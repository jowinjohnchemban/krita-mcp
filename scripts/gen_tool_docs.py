#!/usr/bin/env python3
"""Generate docs/tools.md from the MCP server's tool definitions.

Usage:  python scripts/gen_tool_docs.py          # rewrite docs/tools.md
        python scripts/gen_tool_docs.py --check  # exit 1 if docs/tools.md is out of date (CI)
"""
import inspect
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from krita_mcp import __version__, server  # noqa: E402

TARGET = ROOT / "docs" / "tools.md"

GROUPS = [
    ("Documents", ["krita_status", "document_new", "document_open", "document_activate", "document_info",
                   "save_document", "export_image", "document_close", "resize_canvas", "scale_image",
                   "crop_image", "rotate_image", "flip", "flatten_image", "convert_color_space", "set_guides"]),
    ("Seeing and reading the image", ["canvas_snapshot", "analyze_image", "read_pixels", "sample_color",
                                      "find_color", "view_image", "list_workspace"]),
    ("Layers", ["list_layers", "create_layer", "update_layer", "arrange_layer", "merge_down", "delete_layer",
                "duplicate_layer", "transform_layer", "import_image", "import_image_from_url"]),
    ("Painting and drawing", ["brush_stroke", "list_brush_presets", "draw_shapes", "add_svg",
                              "list_vector_shapes", "remove_vector_shapes", "colorize_lineart"]),
    ("Photo editing", ["adjust_image", "auto_enhance", "add_vignette", "apply_filter", "list_filters",
                       "describe_filter"]),
    ("Selections", ["set_selection", "modify_selection", "fill_selection", "export_selection_mask"]),
    ("Animation and video", ["animation_info", "animation_set", "keyframe", "list_keyframes", "import_frames",
                             "animation_contact_sheet", "export_animation_frames", "video_info", "import_video",
                             "render_video", "for_each_frame"]),
    ("Controls", ["krita_action", "view_control", "notify_user", "user_tool_state"]),
    ("Resources", ["list_resources", "palette_colors"]),
    ("History and batching", ["undo", "redo", "history", "batch"]),
]


def _sig(fn):
    parts = []
    for name, prm in inspect.signature(fn).parameters.items():
        ann = prm.annotation
        t = getattr(ann, "__name__", None) or str(ann).replace("typing.", "")
        t = t.replace("Optional[", "").rstrip("]") if "Optional[" in t else t
        if prm.default is inspect.Parameter.empty:
            parts.append("`%s`: %s" % (name, t))
        else:
            parts.append("`%s`: %s = `%r`" % (name, t, prm.default))
    return parts


def render():
    tools = dict(server.TOOLS)
    grouped = [name for _, names in GROUPS for name in names]
    missing = sorted(set(tools) - set(grouped))
    unknown = sorted(set(grouped) - set(tools))
    if unknown:
        raise SystemExit("gen_tool_docs: listed but not defined: %s" % unknown)
    groups = GROUPS + ([("Other", missing)] if missing else [])
    out = ["# Tool reference", "",
           "<!-- generated by scripts/gen_tool_docs.py - do not edit by hand -->", "",
           "krita-mcp %s exposes **%d tools**. Layers can be referenced by id or (unique) name; coordinates are "
           "canvas pixels from the top-left; colours are `#rrggbb` or `#rrggbbaa`." % (__version__, len(tools)), ""]
    for title, names in groups:
        out.append("- [%s](#%s)" % (title, title.lower().replace(" ", "-")))
    out.append("")
    for title, names in groups:
        out += ["## " + title, ""]
        for name in names:
            fn = tools[name]
            out += ["### `%s`" % name, ""]
            out += [inspect.cleandoc(fn.__doc__ or "").replace("\n", "  \n"), ""]
            sig = _sig(fn)
            if sig:
                out += ["Parameters: " + ", ".join(sig), ""]
    return "\n".join(out).rstrip() + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print("docs/tools.md is out of date: run python scripts/gen_tool_docs.py")
            sys.exit(1)
        return
    TARGET.parent.mkdir(exist_ok=True)
    TARGET.write_text(text, encoding="utf-8")
    print("wrote", TARGET)


if __name__ == "__main__":
    main()
